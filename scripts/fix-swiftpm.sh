#!/bin/bash
# Repairs two Command Line Tools packaging bugs so `swift build` / `swift test`
# work on this machine. Nothing outside .build-toolchain/ is modified.
#
# Bug 1 — stale duplicate modulemap
#   /Library/Developer/CommandLineTools/usr/include/swift/module.modulemap
#   is left over from an older CLT and also defines `SwiftBridging`, which the
#   current bridging.modulemap already defines. Every Swift file that imports
#   Foundation dies with "redefinition of module 'SwiftBridging'".
#   Fix: a VFS overlay that maps that one file to an empty modulemap.
#
# Bug 2 — mismatched libPackageDescription
#   The dylib was built when `swiftLanguageVersions` was typed
#   [SwiftLanguageMode]; the shipped .swiftinterface spells it [SwiftVersion].
#   Same type, different mangled name, so compiling Package.swift asks for a
#   symbol the dylib never exported.
#   Fix: a shim dylib that re-exports the real one and aliases the missing names.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/.build-toolchain"
TOOLCHAIN="/Library/Developer/CommandLineTools"
MANIFEST_API="$TOOLCHAIN/usr/lib/swift/pm/ManifestAPI"
REAL_DYLIB="$MANIFEST_API/libPackageDescription.dylib"
SWIFTC="$TOOLCHAIN/usr/bin/swiftc"
STALE_MODULEMAP="$TOOLCHAIN/usr/include/swift/module.modulemap"
SWIFT_INCLUDE="$TOOLCHAIN/usr/include/swift"

mkdir -p "$OUT"

if [ ! -x "$SWIFTC" ]; then
    echo "找不到 $SWIFTC，这台机器没有装 Command Line Tools" >&2
    exit 1
fi

# ---------------------------------------------------------------- bug 1: VFS
OVERLAY="$OUT/modulemap-overlay.yaml"
: > "$OUT/empty.modulemap"

{
    echo "version: 0"
    echo "roots:"
    echo "  - name: \"$SWIFT_INCLUDE\""
    echo "    type: directory"
    echo "    contents:"
    echo "      - name: \"module.modulemap\""
    echo "        type: file"
    echo "        external-contents: \"$OUT/empty.modulemap\""
    for entry in bridging bridging.modulemap; do
        if [ -e "$SWIFT_INCLUDE/$entry" ]; then
            echo "      - name: \"$entry\""
            echo "        type: file"
            echo "        external-contents: \"$SWIFT_INCLUDE/$entry\""
        fi
    done
} > "$OVERLAY"

# ------------------------------------------------------- bug 2: dylib alias
PROBE_DIR="$(mktemp -d)"
trap 'rm -rf "$PROBE_DIR"' EXIT

cat > "$PROBE_DIR/Package.swift" <<'PROBE'
// swift-tools-version: 6.0
import PackageDescription
let package = Package(
    name: "Probe",
    platforms: [.macOS(.v13)],
    products: [.executable(name: "Probe", targets: ["Probe"])],
    targets: [.executableTarget(name: "Probe", path: "Sources/Probe")]
)
PROBE

SDK="$(xcrun --show-sdk-path)"
TARGET="$(uname -m)-apple-macosx13.0"

"$SWIFTC" -c -swift-version 6 \
    -sdk "$SDK" -target "$TARGET" \
    -vfsoverlay "$OVERLAY" \
    -package-description-version 6.0.0 \
    -I "$MANIFEST_API" \
    -o "$PROBE_DIR/probe.o" \
    "$PROBE_DIR/Package.swift"

MISSING="$(nm -u "$PROBE_DIR/probe.o" | grep -o '_\$s[A-Za-z0-9_]*' | grep 'SwiftVersionO' || true)"

ALIAS_ARGS=()
FOUND=0
if [ -n "$MISSING" ]; then
    for symbol in $MISSING; do
        candidate="$(echo "$symbol" | sed 's/AA12SwiftVersionO/AA05SwiftN4ModeO/g')"
        if nm -gU "$REAL_DYLIB" 2>/dev/null | grep -qF "$candidate"; then
            ALIAS_ARGS+=(-alias "$candidate" "$symbol")
            FOUND=$((FOUND + 1))
        fi
    done
fi

if [ "$FOUND" -gt 0 ]; then
    ld -dylib -arch "$(uname -m)" \
        -platform_version macos 13.0 15.0 \
        -undefined dynamic_lookup \
        -o "$OUT/libPackageDescription.dylib" \
        "${ALIAS_ARGS[@]}" \
        -reexport_library "$REAL_DYLIB"
    echo "已修补 libPackageDescription（$FOUND 个符号别名）"
else
    rm -f "$OUT/libPackageDescription.dylib"
    echo "libPackageDescription 没有符号问题，跳过"
fi

cat > "$OUT/swiftc" <<WRAPPER
#!/bin/bash
# Generated by scripts/fix-swiftpm.sh. Adds the modulemap overlay to every
# compile, the swift-testing framework path, and the dylib shim for manifests.
REAL_DYLIB="$REAL_DYLIB"
SWIFTC="$SWIFTC"
OVERLAY="$OVERLAY"
SHIM_DIR="$OUT"
FRAMEWORKS="$TOOLCHAIN/Library/Developer/Frameworks"
IS_MANIFEST=0
for arg in "\$@"; do
    if [ "\$arg" = "-package-description-version" ]; then
        IS_MANIFEST=1
    fi
done
if [ "\$IS_MANIFEST" = "1" ]; then
    exec "\$SWIFTC" -L"\$SHIM_DIR" -vfsoverlay "\$OVERLAY" -F "\$FRAMEWORKS" -Xlinker -rpath -Xlinker "\$FRAMEWORKS" "\$@" "\$REAL_DYLIB"
fi
exec "\$SWIFTC" -vfsoverlay "\$OVERLAY" -F "\$FRAMEWORKS" -Xlinker -rpath -Xlinker "\$FRAMEWORKS" "\$@"
WRAPPER
chmod +x "$OUT/swiftc"

echo "已生成 $OUT/swiftc"
echo "用 scripts/swift.sh 调用 swift，或手动设置："
echo "  export SWIFT_EXEC=$OUT/swiftc"
